#include <iostream>

int main(){

    int a= 21;
    int b= 4;


    int add = a + b ;
    int sub = a - b ;
    int multi = a * b;
    int div = a / b ;
    int rem = a % b;


    std:: cout<< "Addition - "<< add << std::endl;
    std:: cout<< "Substraction - "<< sub << std::endl;
    std:: cout<< "Multiplication - "<< multi << std::endl;
    std:: cout<< "Division - "<< div << std::endl;
    std:: cout<< "Remainder - "<< rem << std::endl;

    return 0;
}